def write_scene_script(
    built: BuiltScene,
    path: str | Path,
    *,
    folder: str = "ServerStorage.LinenAnimations",
    sheet: SpottingSheet | None = None,
    mapping: dict[str, str] | None = None,
    animations: dict[str, str] | None = None,
) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        scene_script(
            built, folder=folder, sheet=sheet, mapping=mapping, animations=animations
        )
    )
    return path


def _facing_literal(facing: str | float | None) -> str:
    if facing is None:
        return "nil"
    if isinstance(facing, str):
        return f'"{_escape(facing)}"'
    return f"{float(facing):g}"


def _escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")
