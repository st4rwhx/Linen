SKELETONS: dict[str, SkeletonMapping] = {MIXAMO.name: MIXAMO, ROBLOX_R15.name: ROBLOX_R15}
for _mapping in list(SKELETONS.values()):
    for _alias in _mapping.aliases:
        SKELETONS[_alias] = _mapping


def get_skeleton(name: str) -> SkeletonMapping:
    try:
        return SKELETONS[name.lower()]
    except KeyError:
        raise ValueError(
            f"unknown skeleton {name!r}; known: {', '.join(sorted(SKELETONS))}"
        ) from None


def to_landmark_track(
    motion: BvhMotion,
    mapping: SkeletonMapping,
    *,
    units: str = "cm",
    fps: float | None = None,
) -> LandmarkTrack:
    """Convert parsed BVH into a landmark track in Roblox axes and metres."""
    scale = {"mm": 0.001, "cm": 0.01, "m": 1.0}
    if units not in scale:
        raise ValueError(f"unknown units {units!r}; expected one of {', '.join(scale)}")

    missing = mapping.missing_required(motion.names)
    if missing:
        raise ValueError(
            f"{mapping.name}: this file has no joint for {', '.join(missing)}. "
            f"Joints present: {', '.join(motion.names[:12])}…"
        )

    world = motion.world_positions() * scale[units]
    index = {name: i for i, name in enumerate(motion.names)}
    resolved = mapping.resolve(motion.names)

    frames = world.shape[0]
    positions = np.full((frames, len(MEDIAPIPE_POSE), 3), np.nan)
    for landmark, joint in resolved.items():
        positions[:, MEDIAPIPE_POSE.index(landmark), :] = world[:, index[joint]]

    _reconstruct_heels(positions)
    _reconstruct_ears(positions, world, index, mapping)

    # BVH is Y-up right-handed, the same convention Roblox uses.
    return LandmarkTrack(positions, fps if fps is not None else motion.fps)


def _reconstruct_heels(positions: np.ndarray) -> None:
    """Put each heel under its ankle at toe height."""
    for side in ("left", "right"):
        ankle = positions[:, MEDIAPIPE_POSE.index(f"{side}_ankle"), :]
        toe = positions[:, MEDIAPIPE_POSE.index(f"{side}_foot_index"), :]
        heel = ankle.copy()
        heel[:, 1] = toe[:, 1]
        positions[:, MEDIAPIPE_POSE.index(f"{side}_heel"), :] = heel


def _reconstruct_ears(
    positions: np.ndarray,
    world: np.ndarray,
    index: dict[str, int],
    mapping: SkeletonMapping,
) -> None:
    """Place ears either side of the head, along the body's lateral axis."""
    head = next((index[n] for n in mapping.joints["nose"] if n in index), None)
    tip = next((index[n] for n in mapping.head_tip if n in index), None)
    if head is None or tip is None:
        return

    head_pos = world[:, head]
    head_up = normalize(world[:, tip] - head_pos)

    left_shoulder = positions[:, MEDIAPIPE_POSE.index("left_shoulder"), :]
    right_shoulder = positions[:, MEDIAPIPE_POSE.index("right_shoulder"), :]
    hips = 0.5 * (
        positions[:, MEDIAPIPE_POSE.index("left_hip"), :]
        + positions[:, MEDIAPIPE_POSE.index("right_hip"), :]
    )
    spine_up = normalize(0.5 * (left_shoulder + right_shoulder) - hips)
    back = normalize(np.cross(normalize(right_shoulder - left_shoulder), spine_up))

    lateral = normalize(np.cross(head_up, back))
    reach = 0.5 * np.linalg.norm(world[:, tip] - head_pos, axis=-1, keepdims=True)

    positions[:, MEDIAPIPE_POSE.index("left_ear"), :] = head_pos - lateral * reach
    positions[:, MEDIAPIPE_POSE.index("right_ear"), :] = head_pos + lateral * reach
