"""Map a foreign skeleton's joints onto the landmark names the rigs reference.

The retargeter works on named points, not on any particular tracker, so a
skeleton from somewhere else only needs a name mapping to become a
:class:`~linen.retarget.landmarks.LandmarkTrack`.  That is what lets a clip
generated by an external text-to-motion model — SayMotion, a locally run
MoMask or MDM, a Mixamo download — go through exactly the same solve, the same
conventions and the same exporter as a FreeMoCap capture.

Two landmarks MediaPipe provides have no equivalent on an animation skeleton
and are reconstructed instead:

* **heels**, placed under the ankle at toe height, so the foot's forward
  direction comes out horizontal rather than pitched down towards the toe;
* **ears**, placed either side of the head using the head bone's own direction.
  Head pitch and roll survive this; head *yaw* does not, and follows the chest.
  Recovering it would need the source's rotation channels, which are expressed
  against each exporter's own rest pose — not worth binding the solver to.

Because every joint rotation is solved relative to its parent, which way the
source skeleton faces does not matter.  Only baked root motion notices.
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np

from ..math3d import normalize
from ..retarget.landmarks import MEDIAPIPE_POSE, LandmarkTrack
from .bvh import BvhMotion

#: Landmarks the solver can manage without. A part whose source landmarks are
#: missing holds its parent's pose rather than guessing.
OPTIONAL = frozenset({"left_index", "right_index", "left_pinky", "right_pinky", "nose"})


@dataclass(frozen=True)
class SkeletonMapping:
    """A named correspondence from source joints to MediaPipe landmarks."""

    name: str
    #: landmark name -> candidate source joint names, first match wins.
    joints: dict[str, tuple[str, ...]]
    #: Source joint marking the top of the head, used to reconstruct ears.
    head_tip: tuple[str, ...] = ()
    notes: str = ""
    aliases: tuple[str, ...] = field(default=())

    def resolve(self, available: tuple[str, ...]) -> dict[str, str]:
        """Pick the source joint for each landmark, given what the file has."""
        lookup = {name.lower(): name for name in available}
        resolved: dict[str, str] = {}
        for landmark, candidates in self.joints.items():
            for candidate in candidates:
                match = lookup.get(candidate.lower())
                if match is not None:
                    resolved[landmark] = match
                    break
        return resolved

    def missing_required(self, available: tuple[str, ...]) -> list[str]:
        resolved = self.resolve(available)
        return sorted(set(self.joints) - set(resolved) - OPTIONAL)


